// Works out the scaling constants for boardTexture() and writes src/boardTextureScales.js.
// For each board size, the lowest and highest raw connectedness, wetness and dynamism over every
// suit-distinct board, with no dead cards. Run with: node scripts/board-texture-scales.js
// The boards are split across worker threads; min and max combine exactly, so the split doesn't matter.
import { writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { fileURLToPath } from 'node:url';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { loadEvaluator, rawTexture } from '../src/boardTexture.js';

const RANKS = '23456789TJQKA';
const SUITS = 'shdc';
const KEYS = { 3: ['connectedness', 'wetness', 'dynamism'], 4: ['connectedness', 'wetness', 'dynamism'], 5: ['connectedness', 'wetness'] };

/**
 * One board per suit-isomorphism class of the given size, as card strings. Two boards are isomorphic
 * when relabelling the suits turns one into the other, which is when their four per-suit rank masks
 * are the same multiset. Gives 1,755 flops, 16,432 turns and 134,459 rivers.
 */
export function suitDistinctBoards(size) {
  const seen = new Set();
  const boards = [];
  const cards = [];
  const suits = [0, 0, 0, 0];
  const visit = start => {
    if (cards.length === size) {
      const key = [...suits].sort((a, b) => a - b).reduce((k, mask) => k * 8192 + mask, 0);
      if (!seen.has(key)) {
        seen.add(key);
        boards.push(cards.map(c => RANKS[c >> 2] + SUITS[c & 3]));
      }
      return;
    }
    for (let c = start; c < 52; c++) {
      cards.push(c);
      suits[c & 3] ^= 1 << (c >> 2);
      visit(c + 1);
      suits[c & 3] ^= 1 << (c >> 2);
      cards.pop();
    }
  };
  visit(0);
  return boards;
}

function emptyRanges(keys) {
  return Object.fromEntries(keys.map(key => [key, { min: Infinity, max: -Infinity }]));
}

function mergeRanges(target, source) {
  for (const [key, { min, max }] of Object.entries(source)) {
    target[key].min = Math.min(target[key].min, min);
    target[key].max = Math.max(target[key].max, max);
  }
  return target;
}

// The min and max of each raw value over every `step`th board, starting at `offset`
async function rangesOf(size, offset, step) {
  await loadEvaluator();
  const keys = KEYS[size];
  const ranges = emptyRanges(keys);
  const boards = suitDistinctBoards(size);
  for (let i = offset; i < boards.length; i += step) {
    const raw = rawTexture(boards[i]);
    for (const key of keys) {
      if (raw[key] < ranges[key].min) ranges[key].min = raw[key];
      if (raw[key] > ranges[key].max) ranges[key].max = raw[key];
    }
  }
  return ranges;
}

/** The scaling constants for each size: the number of suit-distinct boards and each raw value's min and max. */
export async function computeTextureScales(sizes = [3, 4, 5], threads = availableParallelism()) {
  const result = {};
  for (const size of sizes) {
    const parts = await Promise.all(Array.from({ length: threads }, (_, offset) => new Promise((resolve, reject) => {
      const worker = new Worker(new URL(import.meta.url), { workerData: { boardTextureScales: { size, offset, step: threads } } });
      worker.once('message', resolve);
      worker.once('error', reject);
      worker.once('exit', code => reject(new Error(`Worker exited with code ${code} before replying`)));
    })));
    const ranges = parts.reduce(mergeRanges, emptyRanges(KEYS[size]));
    result[size] = { boards: suitDistinctBoards(size).length, ...ranges };
  }
  return result;
}

export function formatScales(scales) {
  const body = JSON.stringify(scales, null, 2).replace(/"(\w+)":/g, '$1:');
  return `// Generated by scripts/board-texture-scales.js. Do not edit by hand: rerun the script.
// For each board size: how many suit-distinct boards there are, and the lowest and highest raw value
// of each scaled score over them. boardTexture() maps that min to 0 and that max to 1.
export const BOARD_TEXTURE_SCALES = ${body};
`;
}

if (!isMainThread && workerData?.boardTextureScales) {
  const { size, offset, step } = workerData.boardTextureScales;
  parentPort.postMessage(await rangesOf(size, offset, step));
} else if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const start = Date.now();
  const scales = await computeTextureScales();
  const target = new URL('../src/boardTextureScales.js', import.meta.url);
  writeFileSync(target, formatScales(scales));
  console.log(`Wrote ${fileURLToPath(target)} in ${((Date.now() - start) / 1000).toFixed(1)} s`);
}
